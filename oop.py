class Food:
    def __init__(self, food_name, food_type):
        self.food_name = food_name
        self.food_type = food_type


    def display_food(self):
        print ("Food Name:", self.food_name)
        print ("Food Type:", self.food_type)

spaghetti = Food("Spaghetti", "carbohydrate")  
spaghetti.display_food()

